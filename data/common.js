const REGIONS = {};
const REGION_ORDER = [];
const REGION_REQUIRED = ['id', 'short', 'name', 'office', 'basis', 'terms', 'offices', 'programs', 'orgs', 'sources', 'verifiedAt'];

function registerRegion(r) {
  const missing = REGION_REQUIRED.filter(k => r[k] === undefined);
  if (missing.length) { console.error('[선생님 곁에] 지역 데이터 누락:', r.id, missing); return; }
  const missingTerms = Object.keys(NEUTRAL_TERMS).filter(k => !r.terms[k]);
  // 확인되지 않은 용어는 중립 문구로 채워요(다른 지역 값으로 대체하지 않음)
  missingTerms.forEach(k => { r.terms[k] = NEUTRAL_TERMS[k]; });
  REGIONS[r.id] = r;
  if (!REGION_ORDER.includes(r.id)) REGION_ORDER.push(r.id);
}
